"""Задача 2. Простые события.

Вероятность срыва срока поставки товара поставщиком равна 0,14. В этом случае
фирма несёт убыток 600 руб., связанный с дефицитом товара. Определите убыток
фирмы при 30 поставках. Какое произойдёт событие, если для одной из поставок
z = 0,20 (z — случайная величина, равномерно распределённая на (0, 1))?
"""

from random_numbers import simple_events

P = 0.14       # вероятность срыва поставки
LOSS = 600     # убыток от одного срыва, руб.
N = 30         # количество поставок

if __name__ == '__main__':
    result = simple_events(P, N)
    failures = result.counts['A']
    print(f'Сорвано поставок: {failures} из {N}, убыток {failures * LOSS} руб.')
    print(f'В среднем ожидается {N * P:.1f} срывов и {N * P * LOSS:.0f} руб. убытка.')

    # Событие «срыв» происходит, если z < p
    z = 0.20
    if z < P:
        print(f'\nz = {z} < p = {P}: поставка сорвана, убыток {LOSS} руб.')
    else:
        print(f'\nz = {z} ≥ p = {P}: поставка пришла вовремя, убытка нет.')
